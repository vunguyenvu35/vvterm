#!/usr/bin/env bash
# Generates docs/TestInventory.md: the exact list of automated test cases (Go, frontend, E2E).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/docs/TestInventory.md"
cd "$ROOT"
{
  echo "# Test inventory"
  echo
  echo "> Generated by \`scripts/test-inventory.sh\`. Do not edit by hand."
  echo
  echo "## Go (unit + integration)"
  total=0
  for pkg in $(go list ./... ); do
    names=$(go test -list '.*' "$pkg" 2>/dev/null | grep -E '^(Test|Fuzz|Benchmark)' || true)
    [ -z "$names" ] && continue
    n=$(echo "$names" | wc -l | tr -d ' ')
    total=$((total + n))
    echo
    echo "### \`${pkg#vvterm/}\` ($n)"
    echo
    echo "$names" | sed 's/^/- /'
  done
  echo
  echo "**Go test functions: $total** (table-driven cases and sub-tests are extra)."
  echo
  echo "## Frontend (Vitest)"
  echo
  (cd frontend && npx vitest list 2>/dev/null | sed 's/^/- /' | sed 's/ > / › /g') || true
  echo
  echo "## End-to-end (Playwright, real backend)"
  echo
  grep -E "^  step\(|^  const step|step\('" e2e/walkthrough.mjs | sed -E "s/.*step\('(.*)'\).*/- \1/" | grep -v '^  '
} > "$OUT"
echo "wrote $OUT"
