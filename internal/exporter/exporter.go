// Package exporter writes VVTerm data in standard formats: OpenSSH config files,
// plain metadata JSON and password-encrypted backups.
package exporter

import (
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	"vvterm/internal/domain"
	"vvterm/internal/vault"
)

// KeyProvider returns the private key PEM of an identity (only called when keys are exported).
type KeyProvider func(identityID string) ([]byte, error)

// SSHReport lists what an ssh-config export produced.
type SSHReport struct {
	Files    []string
	KeyFiles []string
	Warnings []string
}

var unsafe = regexp.MustCompile(`[^A-Za-z0-9._-]+`)

func sanitize(s string) string {
	s = strings.Trim(unsafe.ReplaceAllString(s, "-"), "-.")
	if s == "" {
		return "unnamed"
	}
	return s
}

// SSHConfig writes dir/config (with an Include for dir/config.d/*), one file per group
// in config.d, and ungrouped hosts in dir/config. Private keys are written to dir/keys
// (mode 0600) only when withKeys is true.
func SSHConfig(dir string, d domain.Data, withKeys bool, keys KeyProvider) (SSHReport, error) {
	var rep SSHReport
	if err := os.MkdirAll(filepath.Join(dir, "config.d"), 0o700); err != nil {
		return rep, err
	}
	hosts := map[string]domain.Host{}
	var live []domain.Host
	for _, h := range d.Hosts {
		if h.Deleted() {
			continue
		}
		if strings.ContainsAny(h.Hostname+h.Username, " \t\r\n\x00") {
			rep.Warnings = append(rep.Warnings, fmt.Sprintf("%s: skipped, hostname/username contain whitespace or control characters", h.Label))
			continue
		}
		hosts[h.ID] = h
		live = append(live, h)
	}
	sort.SliceStable(live, func(i, j int) bool { return live[i].Label < live[j].Label })
	groups := map[string]string{}
	for _, g := range d.Groups {
		if !g.Deleted() {
			groups[g.ID] = g.Name
		}
	}
	idents := map[string]domain.Identity{}
	for _, x := range d.Identities {
		if !x.Deleted() {
			idents[x.ID] = x
		}
	}
	fwds := map[string][]domain.PortForward{}
	for _, f := range d.Forwards {
		if !f.Deleted() {
			fwds[f.HostID] = append(fwds[f.HostID], f)
		}
	}

	// unique aliases
	alias := map[string]string{}
	used := map[string]bool{}
	for _, h := range live {
		a := sanitize(h.Label)
		for n := 2; used[a]; n++ {
			a = fmt.Sprintf("%s-%d", sanitize(h.Label), n)
		}
		used[a] = true
		alias[h.ID] = a
	}

	bodies := map[string]*strings.Builder{} // group name ("" = main config) -> text
	for _, h := range live {
		gname := groups[h.GroupID]
		b := bodies[gname]
		if b == nil {
			b = &strings.Builder{}
			bodies[gname] = b
		}
		if meta := metaLine(h); meta != "" {
			b.WriteString(meta + "\n")
		}
		fmt.Fprintf(b, "Host %s\n    HostName %s\n    Port %d\n", alias[h.ID], h.Hostname, h.Port)
		if h.Username != "" {
			fmt.Fprintf(b, "    User %s\n", h.Username)
		}
		if h.KeepaliveSec > 0 {
			fmt.Fprintf(b, "    ServerAliveInterval %d\n", h.KeepaliveSec)
		}
		if chain := jumpChain(h, hosts, alias); len(chain) > 0 {
			fmt.Fprintf(b, "    ProxyJump %s\n", strings.Join(chain, ","))
		}
		if h.IdentityID != "" {
			id, ok := idents[h.IdentityID]
			switch {
			case !ok:
			case id.AuthType == domain.AuthKey && withKeys && keys != nil:
				pem, err := keys(id.ID)
				if err != nil {
					rep.Warnings = append(rep.Warnings, fmt.Sprintf("%s: key not exported: %v", h.Label, err))
					break
				}
				kdir := filepath.Join(dir, "keys")
				if err := os.MkdirAll(kdir, 0o700); err != nil {
					return rep, err
				}
				kp := filepath.Join(kdir, sanitize(id.Name)+"_"+id.ID[:8])
				if err := os.WriteFile(kp, pem, 0o600); err != nil {
					return rep, err
				}
				_ = os.Chmod(kp, 0o600)
				rep.KeyFiles = appendUnique(rep.KeyFiles, kp)
				fmt.Fprintf(b, "    IdentityFile %s\n", kp)
			case id.AuthType == domain.AuthPassword:
				fmt.Fprintf(b, "    # password identity %q cannot be represented in ssh config\n", id.Name)
			case id.AuthType == domain.AuthKey:
				fmt.Fprintf(b, "    # key identity %q not exported (keys excluded)\n", id.Name)
			}
		}
		for _, f := range fwds[h.ID] {
			bind := f.BindAddr
			if bind == "" {
				bind = "127.0.0.1"
			}
			switch f.Type {
			case domain.ForwardLocal:
				fmt.Fprintf(b, "    LocalForward %s:%d %s:%d\n", bind, f.BindPort, f.DestHost, f.DestPort)
			case domain.ForwardRemote:
				fmt.Fprintf(b, "    RemoteForward %s:%d %s:%d\n", bind, f.BindPort, f.DestHost, f.DestPort)
			case domain.ForwardDynamic:
				fmt.Fprintf(b, "    DynamicForward %s:%d\n", bind, f.BindPort)
			}
		}
		b.WriteString("\n")
	}

	main := &strings.Builder{}
	main.WriteString("# Generated by VVTerm on " + time.Now().UTC().Format(time.RFC3339) + "\nInclude config.d/*\n\n")
	if b := bodies[""]; b != nil {
		main.WriteString(b.String())
	}
	cfg := filepath.Join(dir, "config")
	if err := os.WriteFile(cfg, []byte(main.String()), 0o600); err != nil {
		return rep, err
	}
	rep.Files = append(rep.Files, cfg)

	var names []string
	for g := range bodies {
		if g != "" {
			names = append(names, g)
		}
	}
	sort.Strings(names)
	usedFiles := map[string]bool{}
	for _, g := range names {
		fn := sanitize(g)
		for n := 2; usedFiles[fn]; n++ {
			fn = fmt.Sprintf("%s-%d", sanitize(g), n)
		}
		usedFiles[fn] = true
		if fn == "config" {
			fn = "config-group"
		}
		p := filepath.Join(dir, "config.d", fn)
		if err := os.WriteFile(p, []byte(bodies[g].String()), 0o600); err != nil {
			return rep, err
		}
		rep.Files = append(rep.Files, p)
	}
	return rep, nil
}

func appendUnique(xs []string, v string) []string {
	for _, x := range xs {
		if x == v {
			return xs
		}
	}
	return append(xs, v)
}

func metaLine(h domain.Host) string {
	var parts []string
	if h.Env != "" {
		parts = append(parts, "env="+string(h.Env))
	}
	if len(h.Tags) > 0 {
		parts = append(parts, "tags="+strings.Join(h.Tags, ","))
	}
	if len(parts) == 0 {
		return ""
	}
	return "# vvterm: " + strings.Join(parts, " ")
}

func jumpChain(h domain.Host, hosts map[string]domain.Host, alias map[string]string) []string {
	var rev []string
	seen := map[string]bool{h.ID: true}
	for id := h.JumpHostID; id != "" && len(rev) < 8; {
		j, ok := hosts[id]
		if !ok || seen[id] {
			break
		}
		seen[id] = true
		rev = append(rev, alias[id])
		id = j.JumpHostID
	}
	out := make([]string, len(rev))
	for i, a := range rev {
		out[len(rev)-1-i] = a
	}
	return out
}

// PlainJSON returns metadata only: no secrets, no tombstones, no secret references.
func PlainJSON(d domain.Data) ([]byte, error) {
	out := domain.Data{Version: d.Version}
	for _, g := range d.Groups {
		if !g.Deleted() {
			out.Groups = append(out.Groups, g)
		}
	}
	for _, h := range d.Hosts {
		if !h.Deleted() {
			out.Hosts = append(out.Hosts, h)
		}
	}
	for _, f := range d.Forwards {
		if !f.Deleted() {
			out.Forwards = append(out.Forwards, f)
		}
	}
	for _, x := range d.Identities {
		if !x.Deleted() {
			x.SecretRef = ""
			out.Identities = append(out.Identities, x)
		}
	}
	for _, x := range d.Snippets {
		if !x.Deleted() {
			out.Snippets = append(out.Snippets, x)
		}
	}
	return json.MarshalIndent(out, "", "  ")
}

// Backup is the plaintext inside an encrypted backup file.
type Backup struct {
	Version    int                 `json:"version"`
	ExportedAt time.Time           `json:"exported_at"`
	Data       domain.Data         `json:"data"`
	Secrets    []vault.PlainSecret `json:"secrets"`
}

const MinBackupPasswordLen = 8

// EncryptBackup seals data and secrets with an independent backup password.
func EncryptBackup(pw string, d domain.Data, secrets []vault.PlainSecret) ([]byte, error) {
	if len(pw) < MinBackupPasswordLen {
		return nil, fmt.Errorf("backup password must be at least %d characters", MinBackupPasswordLen)
	}
	plain, err := json.Marshal(Backup{Version: 1, ExportedAt: time.Now().UTC(), Data: d, Secrets: secrets})
	if err != nil {
		return nil, err
	}
	return vault.SealWithPassword(pw, plain, vault.DefaultKDF())
}

// DecryptBackup reverses EncryptBackup.
func DecryptBackup(pw string, blob []byte) (*Backup, error) {
	plain, err := vault.OpenWithPassword(pw, blob)
	if err != nil {
		return nil, err
	}
	var b Backup
	if err := json.Unmarshal(plain, &b); err != nil {
		return nil, fmt.Errorf("corrupt backup: %w", err)
	}
	if b.Version != 1 {
		return nil, errors.New("unsupported backup version " + strconv.Itoa(b.Version))
	}
	return &b, nil
}
